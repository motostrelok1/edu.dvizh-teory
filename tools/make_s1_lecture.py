def motivation(text):
    return {'type': 'motivation', 'text': text}


def topic(text):
    return {'type': 'topic', 'text': text}


def lead(text):
    return {'type': 'lead', 'text': text}


def quote(text):
    return {'type': 'quote', 'text': text}


def term(name, definition, important=False):
    b = {'type': 'term', 'term': name, 'def': definition}
    if important:
        b['important'] = True
    return b


def example(good, title, text):
    return {'type': 'example', 'good': good, 'title': title, 'text': text}


def quiz(intro, questions):
    return {'type': 'quiz', 'intro': intro, 'questions': questions}


